  await page.getByLabel('WhatsApp', { exact: true }).fill('+54 9 343 0000000')
  await page.getByLabel('Correo', { exact: true }).fill('demo@ejemplo.test')
  await page.getByLabel('Foto de perfil', { exact: true }).setInputFiles({ name: 'foto.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64') })
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(page.getByRole('status')).toContainText('Guardaste los cambios')
  await expect(page.getByLabel('Nombre y apellido')).toHaveValue('Julia Demo')
  await expect(page.getByAltText('Tu foto de perfil')).toBeVisible()
  expect(await page.getByAltText('Tu foto de perfil').evaluate((img: HTMLImageElement) => img.naturalWidth)).toBeGreaterThan(0)
