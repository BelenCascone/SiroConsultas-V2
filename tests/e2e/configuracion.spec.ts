test('consultorios: agrega mañana y tarde, edita, apaga y reactiva', async ({ page }) => {
  await page.getByRole('link', { name: 'Consultorios y horarios' }).click()
  await page.getByRole('button', { name: '+ Agregar consultorio' }).click()
  const ventana = page.getByRole('dialog', { name: 'Agregar consultorio', exact: true })
  await ventana.getByLabel('Nombre del consultorio').fill('Sur')
  await ventana.getByLabel('Dirección', { exact: true }).fill('Calle Ficticia 100')
  await ventana.getByLabel('Cómo llegar (opcional)').fill('Timbre 2')
  const lunes = ventana.locator('fieldset.config-dia').filter({ has: page.getByText('Lunes', { exact: true }) })
  await lunes.getByRole('checkbox', { name: 'Lunes' }).check()
  await lunes.getByLabel('Desde').fill('09:00')
  await lunes.getByLabel('Hasta').fill('12:00')
  await lunes.getByRole('button', { name: '+ Otro horario' }).click()
  await lunes.getByLabel('Desde').nth(1).fill('15:00')
  await lunes.getByLabel('Hasta').nth(1).fill('18:00')
  await ventana.getByRole('button', { name: 'Guardar consultorio' }).click()
  await expect(page.getByRole('status')).toContainText('Guardaste')
  const sur = page.getByRole('region', { name: 'Consultorio Sur', exact: true })
  await expect(sur).toContainText('09:00–12:00 y 15:00–18:00')
  await sur.locator('summary').click()
  await sur.getByLabel('Nombre del consultorio').fill('Sur nuevo')
  await sur.getByRole('switch').uncheck()
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  const nuevo = page.getByRole('region', { name: 'Consultorio Sur nuevo', exact: true })
  await expect(nuevo.getByRole('switch')).not.toBeChecked()
  await nuevo.getByRole('switch').check()
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(page.getByRole('region', { name: 'Consultorio Sur nuevo', exact: true }).getByRole('switch')).toBeChecked()
  await page.getByRole('button', { name: '+ Agregar consultorio' }).click()
  await ventana.getByLabel('Nombre del consultorio').fill('Virtual demo')
  await ventana.getByRole('radio', { name: 'Videollamada', exact: true }).check()
  await expect(ventana.getByLabel('Dirección', { exact: true })).toBeHidden()
  await lunes.getByRole('checkbox', { name: 'Lunes' }).check()
  await lunes.getByLabel('Desde').fill('10:00')
  await lunes.getByLabel('Hasta').fill('13:00')
  await ventana.getByRole('button', { name: 'Guardar consultorio' }).click()
  await expect(page.getByRole('region', { name: 'Consultorio Virtual demo', exact: true })).toContainText('Videollamada')
})

