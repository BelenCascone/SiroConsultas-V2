/// <reference lib="dom" />
/// <reference lib="dom.iterable" />
import { test, expect, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'

async function paciente(page:Page) {
  const dni=String(80000000+Math.floor(Math.random()*10000000))
  const id=await page.evaluate(async dni=>{
    const post=async(ruta:string,datos:Record<string,string>)=>fetch(ruta,{method:'POST',body:new URLSearchParams(datos)})
    const r=await post('/pacientes',{dni,nombre:'Paciente',apellido:`Documento ${dni}`,celular:'3430000000',correo:'ficticio@example.test'})
    const id=new URL(r.url).pathname.split('/')[2]
    await post('/consultas/completar-ficha',{paciente:id,turno:'',fecha_nacimiento:'1990-02-10',domicilio:'Calle Ficticia 123',ocupacion:'Docente',cobertura:'particular'})
    return id
  },dni)
  return id
}
test.beforeEach(async({page})=>{
  page.on('pageerror',e=>{throw e})
  await page.goto('/ingresar');await page.getByLabel('Clave de prueba').fill('prueba-e2e-123')
  await page.getByRole('button',{name:'Entrar a la demo'}).click()
  await expect(page).toHaveURL(/\/$/)
})
test('certificado desde la ficha: emisión, re-descarga idéntica, anulación y exportación',async({page})=>{
  const id=await paciente(page)
  await page.goto(`/pacientes/${id}`)
  await page.getByRole('button',{name:'Certificado',exact:true}).click()
  const ventana=page.getByRole('dialog',{name:'Certificado',exact:true})
  await ventana.getByLabel('Diagnóstico',{exact:true}).fill('Diagnóstico ficticio: tensión cervical, ñ y β.')
  await ventana.getByLabel('Días de reposo').fill('2')
  await ventana.getByRole('button',{name:'Generar certificado'}).click()
  await expect(ventana.getByRole('heading',{name:'¿Se lo mandás?'})).toBeVisible()
  await expect(ventana.getByRole('link',{name:'Por WhatsApp'})).toHaveAttribute('href',/^https:\/\/wa.me\//)
  // P5: «Por correo» abre el documento, que lo manda con el PDF adjunto.
  await expect(ventana.getByRole('link',{name:'Por correo'})).toHaveAttribute('href',/^\/documentos\/\d+$/)
  const descarga=page.waitForEvent('download');await ventana.getByRole('link',{name:'Descargar PDF'}).click()
  const archivo=await descarga,original=await readFile((await archivo.path())!)
  expect(original.subarray(0,8).toString()).toBe('%PDF-1.7')
  await ventana.getByRole('link',{name:'Ver documento',exact:true}).click()
  const url=page.url()
  const otra=page.waitForEvent('download');await page.getByRole('link',{name:'Descargar PDF',exact:true}).click()
  expect(await readFile((await(await otra).path())!)).toEqual(original)
  await page.getByText('Anular con motivo',{exact:true}).click()
  await page.getByLabel('Motivo de anulación').fill('Error ficticio de carga')
  await page.getByRole('button',{name:'Anular',exact:true}).click()
  await expect(page).toHaveURL(/tab=documentos/)
  await expect(page.locator('del')).toHaveText('Certificado')
  await expect(page.getByText('Anulado: Error ficticio de carga')).toBeVisible()
  await page.goto(url)
  await expect(page.getByText(/Anulado el/)).toBeVisible()
  await page.goto(`/pacientes/${id}?tab=historia`)
  await page.getByRole('link',{name:'Exportar historia clínica',exact:true}).click()
  const zip=page.waitForEvent('download');await page.getByRole('button',{name:'Preparar ZIP'}).click()
  const b=await readFile((await(await zip).path())!)
  expect(b.readUInt32LE(0)).toBe(0x04034b50)
  expect(b.includes(Buffer.from('LEEME.txt'))).toBe(true)
  expect(b.includes(original)).toBe(true)
})
test('emitir durante una consulta guarda el borrador y conserva lo escrito en pantalla',async({page})=>{
  const id=await paciente(page)
  await page.goto(`/consultas/nueva?paciente=${id}`)
  await page.getByLabel('Motivo de consulta y anamnesis').fill('Texto clínico ficticio que sigue en edición')
  await page.getByRole('button',{name:'Pedido de estudios',exact:true}).click()
  const ventana=page.getByRole('dialog',{name:'Pedido de estudios',exact:true})
  await ventana.getByLabel('Estudios o prácticas').fill('Hemograma\nGlucemia')
  await ventana.getByRole('button',{name:'Generar pedido'}).click()
  await expect(ventana.getByRole('heading',{name:'Pedido de estudios guardado en la ficha'})).toBeVisible()
  await ventana.getByRole('button',{name:'Ahora no'}).click()
  await expect(page).toHaveURL(/\/consultas\/\d+$/)
  await expect(page.getByLabel('Motivo de consulta y anamnesis')).toHaveValue('Texto clínico ficticio que sigue en edición')
  await expect(page.locator('[data-consulta-estado]')).toContainText('Borrador guardado')
  const consulta=page.url()
  await page.reload()
  await expect(page.getByLabel('Motivo de consulta y anamnesis')).toHaveValue('Texto clínico ficticio que sigue en edición')
  await page.goto(`/pacientes/${id}?tab=documentos&tipo=pedido`)
  await expect(page.getByRole('listitem').getByRole('link',{name:'Pedido de estudios',exact:true})).toBeVisible()
  await expect(page.getByRole('link',{name:'Consulta',exact:true})).toHaveAttribute('href',new URL(consulta).pathname)
})
test('MisRx registra medicación sin PDF y permite filtrar estudios adjuntos',async({page})=>{
  const id=await paciente(page)
  await page.goto(`/pacientes/${id}?tab=documentos`)
  await page.getByRole('button',{name:'Receta (MisRx)',exact:true}).click()
  const ventana=page.getByRole('dialog',{name:'Receta (MisRx)',exact:true})
  await expect(ventana.getByText('La receta digital se hace en MisRx.')).toBeVisible()
  await ventana.getByLabel('Medicamento',{exact:true}).fill('Medicamento ficticio')
  await ventana.getByLabel('Indicaciones (opcional)').fill('Indicación ficticia')
  await ventana.getByRole('button',{name:'Guardar en la ficha'}).click()
  await expect(ventana.getByRole('heading',{name:'Receta (MisRx) guardado en la ficha'})).toBeVisible()
  await expect(ventana.getByRole('link',{name:'Descargar PDF'})).toBeHidden()
  await ventana.getByRole('button',{name:'Ahora no'}).click()
  await page.getByRole('button',{name:'Adjuntar estudio',exact:true}).click()
  const estudio=page.getByRole('dialog',{name:'Adjuntar estudio',exact:true})
  await estudio.getByLabel('Nombre del estudio').fill('Estudio ficticio adjunto')
  await estudio.getByLabel('Archivo del estudio').setInputFiles({name:'ficticio.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.7\nEstudio ficticio')})
  await estudio.getByRole('button',{name:'Guardar estudio'}).click()
  await expect(estudio.getByRole('heading',{name:'Estudio guardado en la ficha'})).toBeVisible()
  await estudio.getByRole('button',{name:'Ahora no'}).click()
  await page.getByRole('navigation',{name:'Filtrar documentos'}).getByRole('link',{name:'Estudio',exact:true}).click()
  await expect(page.getByRole('link',{name:'Estudio ficticio adjunto',exact:true})).toBeVisible()
  await expect(page.getByRole('listitem').getByRole('link',{name:'Receta (MisRx)',exact:true})).toBeHidden()
})
