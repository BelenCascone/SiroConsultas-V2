test('prestaciones: crea sin cargo, edita importe y desactiva', async ({ page }) => {
  await page.getByRole('link', { name: 'Prestaciones', exact: false }).click()
  await page.getByRole('button', { name: '+ Agregar prestación' }).click()
  const ventana = page.getByRole('dialog', { name: 'Agregar prestación', exact: true })
  await ventana.getByLabel('Nombre de la prestación').fill('Control demo')
  await ventana.getByLabel('Duración (minutos)').fill('20')
  await ventana.getByLabel('Importe particular ($)').fill('0')
  await ventana.getByRole('button', { name: 'Guardar prestación' }).click()
  const registro = page.getByRole('region', { name: 'Control demo', exact: true })
  await expect(registro).toContainText('Sin cargo')
  await registro.getByLabel('Importe particular ($)').fill('12500,50')
  await registro.getByRole('switch').uncheck()
  await page.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(registro).toContainText('$ 12.500,50')
  await expect(registro.getByRole('switch')).not.toBeChecked()
})

